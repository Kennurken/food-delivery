_NO_CONTACTS = {"ru": "через форму «Подключить ресторан» или в приложении",
                "kk": "«Мейрамхананы қосу» формасы немесе қосымша арқылы"}


def sections(doc: str, lang: str, *, operator: str, email: str, phone: str) -> list:
    lang = lang if lang in ("ru", "kk") else "ru"
    contacts = ", ".join(c for c in (email, phone) if c) or _NO_CONTACTS[lang]
    who = operator or _OPERATOR_FALLBACK[lang]
    return [
        (heading, [p.format(operator=who, contacts=contacts) for p in paras])
        for heading, paras in DOCS[doc][lang]
    ]
